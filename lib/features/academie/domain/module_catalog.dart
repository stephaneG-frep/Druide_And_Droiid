enum ModuleLevel {
  debutant('Débutant'),
  intermediaire('Intermédiaire'),
  avance('Avancé'),
  expert('Expert');

  const ModuleLevel(this.label);

  final String label;
}

class AcademyModule {
  const AcademyModule({
    required this.id,
    required this.number,
    required this.title,
    required this.summary,
    required this.level,
    required this.topics,
  });

  final String id;
  final int number;
  final String title;
  final String summary;
  final ModuleLevel level;
  final List<String> topics;
}

AcademyModule? moduleById(String id) {
  for (final module in academyModules) {
    if (module.id == id) return module;
  }
  return null;
}

